PRAGMA foreign_keys=ON;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS suppliers;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS shipments;
DROP TABLE IF EXISTS reviews;
CREATE TABLE categories(category_id INTEGER PRIMARY KEY,name TEXT);
CREATE TABLE suppliers(supplier_id INTEGER PRIMARY KEY,name TEXT);
CREATE TABLE customers(customer_id INTEGER PRIMARY KEY,name TEXT,email TEXT);
CREATE TABLE employees(employee_id INTEGER PRIMARY KEY,name TEXT);
CREATE TABLE products(product_id INTEGER PRIMARY KEY,category_id INT,supplier_id INT,name TEXT,price REAL,FOREIGN KEY(category_id) REFERENCES categories(category_id),FOREIGN KEY(supplier_id) REFERENCES suppliers(supplier_id));
CREATE TABLE orders(order_id INTEGER PRIMARY KEY,customer_id INT,employee_id INT,order_date TEXT,FOREIGN KEY(customer_id) REFERENCES customers(customer_id),FOREIGN KEY(employee_id) REFERENCES employees(employee_id));
CREATE TABLE order_items(item_id INTEGER PRIMARY KEY,order_id INT,product_id INT,qty INT,FOREIGN KEY(order_id) REFERENCES orders(order_id),FOREIGN KEY(product_id) REFERENCES products(product_id));
CREATE TABLE payments(payment_id INTEGER PRIMARY KEY,order_id INT,amount REAL,method TEXT,FOREIGN KEY(order_id) REFERENCES orders(order_id));
CREATE TABLE shipments(shipment_id INTEGER PRIMARY KEY,order_id INT,status TEXT,FOREIGN KEY(order_id) REFERENCES orders(order_id));
CREATE TABLE reviews(review_id INTEGER PRIMARY KEY,customer_id INT,product_id INT,rating INT,FOREIGN KEY(customer_id) REFERENCES customers(customer_id),FOREIGN KEY(product_id) REFERENCES products(product_id));
