PRAGMA foreign_keys=ON;

DROP TABLE IF EXISTS users;

DROP TABLE IF EXISTS profiles;

DROP TABLE IF EXISTS posts;

DROP TABLE IF EXISTS comments;

DROP TABLE IF EXISTS likes;

DROP TABLE IF EXISTS friendships;

DROP TABLE IF EXISTS messages;

DROP TABLE IF EXISTS groups_tbl;

DROP TABLE IF EXISTS group_members;

DROP TABLE IF EXISTS notifications;

CREATE TABLE users(user_id INTEGER PRIMARY KEY,username TEXT,email TEXT);

CREATE TABLE profiles(profile_id INTEGER PRIMARY KEY,user_id INT,bio TEXT);

CREATE TABLE posts(post_id INTEGER PRIMARY KEY,user_id INT,content TEXT);

CREATE TABLE comments(comment_id INTEGER PRIMARY KEY,post_id INT,user_id INT,content TEXT);

CREATE TABLE likes(like_id INTEGER PRIMARY KEY,post_id INT,user_id INT);

CREATE TABLE friendships(friendship_id INTEGER PRIMARY KEY,user1_id INT,user2_id INT,status TEXT);

CREATE TABLE messages(message_id INTEGER PRIMARY KEY,sender_id INT,receiver_id INT,message TEXT);

CREATE TABLE groups_tbl(group_id INTEGER PRIMARY KEY,name TEXT);

CREATE TABLE group_members(id INTEGER PRIMARY KEY,group_id INT,user_id INT);

CREATE TABLE notifications(notification_id INTEGER PRIMARY KEY,user_id INT,message TEXT,status TEXT);

