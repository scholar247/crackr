DROP TABLE IF EXISTS movies;

DROP TABLE IF EXISTS theaters;

DROP TABLE IF EXISTS screens;

DROP TABLE IF EXISTS customers;

DROP TABLE IF EXISTS shows;

DROP TABLE IF EXISTS seats;

DROP TABLE IF EXISTS bookings;

DROP TABLE IF EXISTS tickets;

DROP TABLE IF EXISTS payments;

DROP TABLE IF EXISTS reviews;

CREATE TABLE movies(movie_id INTEGER PRIMARY KEY,title TEXT,genre TEXT,duration INT);

CREATE TABLE theaters(theater_id INTEGER PRIMARY KEY,name TEXT,city TEXT);

CREATE TABLE screens(screen_id INTEGER PRIMARY KEY,theater_id INT,screen_name TEXT);

CREATE TABLE customers(customer_id INTEGER PRIMARY KEY,name TEXT,email TEXT);

CREATE TABLE shows(show_id INTEGER PRIMARY KEY,movie_id INT,screen_id INT,show_time TEXT);

CREATE TABLE seats(seat_id INTEGER PRIMARY KEY,screen_id INT,seat_no TEXT);

CREATE TABLE bookings(booking_id INTEGER PRIMARY KEY,customer_id INT,show_id INT,total REAL);

CREATE TABLE tickets(ticket_id INTEGER PRIMARY KEY,booking_id INT,seat_id INT,price REAL);

CREATE TABLE payments(payment_id INTEGER PRIMARY KEY,booking_id INT,method TEXT,amount REAL);

CREATE TABLE reviews(review_id INTEGER PRIMARY KEY,customer_id INT,movie_id INT,rating INT);

