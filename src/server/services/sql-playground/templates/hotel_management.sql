PRAGMA foreign_keys=ON;

DROP TABLE IF EXISTS hotels;

DROP TABLE IF EXISTS rooms;

DROP TABLE IF EXISTS guests;

DROP TABLE IF EXISTS staff;

DROP TABLE IF EXISTS bookings;

DROP TABLE IF EXISTS payments;

DROP TABLE IF EXISTS services;

DROP TABLE IF EXISTS service_usage;

DROP TABLE IF EXISTS reviews;

DROP TABLE IF EXISTS housekeeping;

CREATE TABLE hotels(hotel_id INTEGER PRIMARY KEY,name TEXT,city TEXT);

CREATE TABLE rooms(room_id INTEGER PRIMARY KEY,hotel_id INT,room_no TEXT,type TEXT);

CREATE TABLE guests(guest_id INTEGER PRIMARY KEY,name TEXT,email TEXT);

CREATE TABLE staff(staff_id INTEGER PRIMARY KEY,hotel_id INT,name TEXT);

CREATE TABLE bookings(booking_id INTEGER PRIMARY KEY,guest_id INT,room_id INT,check_in TEXT);

CREATE TABLE payments(payment_id INTEGER PRIMARY KEY,booking_id INT,amount REAL,method TEXT);

CREATE TABLE services(service_id INTEGER PRIMARY KEY,name TEXT,price REAL);

CREATE TABLE service_usage(usage_id INTEGER PRIMARY KEY,booking_id INT,service_id INT);

CREATE TABLE reviews(review_id INTEGER PRIMARY KEY,guest_id INT,hotel_id INT,rating INT);

CREATE TABLE housekeeping(task_id INTEGER PRIMARY KEY,room_id INT,status TEXT);

