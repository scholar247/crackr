DROP TABLE IF EXISTS branches;

DROP TABLE IF EXISTS customers;

DROP TABLE IF EXISTS employees;

DROP TABLE IF EXISTS accounts;

DROP TABLE IF EXISTS cards;

DROP TABLE IF EXISTS loans;

DROP TABLE IF EXISTS transactions;

DROP TABLE IF EXISTS beneficiaries;

DROP TABLE IF EXISTS transfers;

DROP TABLE IF EXISTS payments;

CREATE TABLE branches(branch_id INTEGER PRIMARY KEY,name TEXT,city TEXT);

CREATE TABLE customers(customer_id INTEGER PRIMARY KEY,name TEXT,email TEXT);

CREATE TABLE employees(employee_id INTEGER PRIMARY KEY,branch_id INT,name TEXT);

CREATE TABLE accounts(account_id INTEGER PRIMARY KEY,customer_id INT,branch_id INT,account_type TEXT,balance REAL);

CREATE TABLE cards(card_id INTEGER PRIMARY KEY,account_id INT,card_type TEXT,status TEXT);

CREATE TABLE loans(loan_id INTEGER PRIMARY KEY,customer_id INT,amount REAL,loan_type TEXT);

CREATE TABLE transactions(transaction_id INTEGER PRIMARY KEY,account_id INT,txn_type TEXT,amount REAL);

CREATE TABLE beneficiaries(beneficiary_id INTEGER PRIMARY KEY,customer_id INT,name TEXT);

CREATE TABLE transfers(transfer_id INTEGER PRIMARY KEY,transaction_id INT,beneficiary_id INT,amount REAL);

CREATE TABLE payments(payment_id INTEGER PRIMARY KEY,account_id INT,bill_type TEXT,amount REAL);

