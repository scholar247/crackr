DROP TABLE IF EXISTS departments;

DROP TABLE IF EXISTS employees;

DROP TABLE IF EXISTS designations;

DROP TABLE IF EXISTS employee_designations;

DROP TABLE IF EXISTS attendance;

DROP TABLE IF EXISTS leave_requests;

DROP TABLE IF EXISTS payroll;

DROP TABLE IF EXISTS projects;

DROP TABLE IF EXISTS employee_projects;

DROP TABLE IF EXISTS performance_reviews;

CREATE TABLE departments(department_id INTEGER PRIMARY KEY,name TEXT);

CREATE TABLE employees(employee_id INTEGER PRIMARY KEY,department_id INT,name TEXT,email TEXT);

CREATE TABLE designations(designation_id INTEGER PRIMARY KEY,title TEXT);

CREATE TABLE employee_designations(id INTEGER PRIMARY KEY,employee_id INT,designation_id INT);

CREATE TABLE attendance(attendance_id INTEGER PRIMARY KEY,employee_id INT,att_date TEXT,status TEXT);

CREATE TABLE leave_requests(leave_id INTEGER PRIMARY KEY,employee_id INT,leave_type TEXT,status TEXT);

CREATE TABLE payroll(payroll_id INTEGER PRIMARY KEY,employee_id INT,salary REAL,month TEXT);

CREATE TABLE projects(project_id INTEGER PRIMARY KEY,name TEXT,department_id INT);

CREATE TABLE employee_projects(id INTEGER PRIMARY KEY,employee_id INT,project_id INT);

CREATE TABLE performance_reviews(review_id INTEGER PRIMARY KEY,employee_id INT,rating INT,review_year INT);

