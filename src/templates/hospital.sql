PRAGMA foreign_keys=ON;

DROP TABLE IF EXISTS departments;

DROP TABLE IF EXISTS doctors;

DROP TABLE IF EXISTS patients;

DROP TABLE IF EXISTS rooms;

DROP TABLE IF EXISTS appointments;

DROP TABLE IF EXISTS admissions;

DROP TABLE IF EXISTS medicines;

DROP TABLE IF EXISTS prescriptions;

DROP TABLE IF EXISTS bills;

DROP TABLE IF EXISTS payments;

CREATE TABLE departments(department_id INTEGER PRIMARY KEY,name TEXT);

CREATE TABLE doctors(doctor_id INTEGER PRIMARY KEY,department_id INT,name TEXT,FOREIGN KEY(department_id) REFERENCES departments(department_id));

CREATE TABLE patients(patient_id INTEGER PRIMARY KEY,name TEXT,gender TEXT);

CREATE TABLE rooms(room_id INTEGER PRIMARY KEY,room_no TEXT,type TEXT);

CREATE TABLE appointments(appointment_id INTEGER PRIMARY KEY,patient_id INT,doctor_id INT,dt TEXT);

CREATE TABLE admissions(admission_id INTEGER PRIMARY KEY,patient_id INT,room_id INT);

CREATE TABLE medicines(medicine_id INTEGER PRIMARY KEY,name TEXT,price REAL);

CREATE TABLE prescriptions(prescription_id INTEGER PRIMARY KEY,appointment_id INT,medicine_id INT,qty INT);

CREATE TABLE bills(bill_id INTEGER PRIMARY KEY,patient_id INT,amount REAL);

CREATE TABLE payments(payment_id INTEGER PRIMARY KEY,bill_id INT,method TEXT);

