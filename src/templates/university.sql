PRAGMA foreign_keys=ON;

DROP TABLE IF EXISTS departments;

DROP TABLE IF EXISTS students;

DROP TABLE IF EXISTS faculty;

DROP TABLE IF EXISTS courses;

DROP TABLE IF EXISTS classrooms;

DROP TABLE IF EXISTS sections;

DROP TABLE IF EXISTS enrollments;

DROP TABLE IF EXISTS exams;

DROP TABLE IF EXISTS results;

DROP TABLE IF EXISTS fees;

CREATE TABLE departments(department_id INTEGER PRIMARY KEY,name TEXT);

CREATE TABLE students(student_id INTEGER PRIMARY KEY,department_id INT,name TEXT,year INT);

CREATE TABLE faculty(faculty_id INTEGER PRIMARY KEY,department_id INT,name TEXT);

CREATE TABLE courses(course_id INTEGER PRIMARY KEY,department_id INT,title TEXT,credits INT);

CREATE TABLE classrooms(classroom_id INTEGER PRIMARY KEY,building TEXT,room_no TEXT);

CREATE TABLE sections(section_id INTEGER PRIMARY KEY,course_id INT,faculty_id INT,classroom_id INT,semester TEXT);

CREATE TABLE enrollments(enrollment_id INTEGER PRIMARY KEY,student_id INT,section_id INT,grade TEXT);

CREATE TABLE exams(exam_id INTEGER PRIMARY KEY,section_id INT,exam_name TEXT,max_marks INT);

CREATE TABLE results(result_id INTEGER PRIMARY KEY,exam_id INT,student_id INT,marks INT);

CREATE TABLE fees(fee_id INTEGER PRIMARY KEY,student_id INT,amount REAL,status TEXT);

